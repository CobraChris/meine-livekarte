'use strict';
// Real Chrome release preflight: installed service worker, offline restart,
// local ticket database, and preserved trip state. Synthetic data only.
// The live phone, actual QR tickets and any remote provider are never touched.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const http=require('node:http');
const {chromium}=require('playwright-core');
const root=path.resolve(__dirname,'..');
const mime={'.html':'text/html; charset=utf-8','.css':'text/css; charset=utf-8',
 '.js':'text/javascript; charset=utf-8','.json':'application/json',
 '.svg':'image/svg+xml','.png':'image/png','.woff2':'font/woff2'};
const tinyPng=Buffer.from(
 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/lQAAAABJRU5ErkJggg==','base64');
function server(){
 return http.createServer(async(req,res)=>{
  try{
   const pathname=new URL(req.url,'http://localhost').pathname;
   const filename=decodeURIComponent(pathname==='/'?'/index.html':pathname);
   if(['icons/livekarte-192.png','icons/livekarte-512.png',
     'icons/livekarte-maskable-512.png'].includes(filename.slice(1))){
    // These files are generated by the separate Pages build; the test
    // substitutes harmless 1px fixture icons, not production artifacts.
    res.writeHead(200,{'content-type':'image/png','cache-control':'no-store'});
    res.end(tinyPng);return;
   }
   if(filename==='/build-version.js'){
    res.writeHead(200,{'content-type':'text/javascript','cache-control':'no-store'});
    res.end("window.LivekarteAppBuild='"+'a'.repeat(40)+"';");return;
   }
   const file=path.resolve(root,'.'+filename);
   if(!file.startsWith(root+path.sep)){res.writeHead(403);res.end();return;}
   const data=await fs.promises.readFile(file);
   res.writeHead(200,{'content-type':mime[path.extname(file)]||'application/octet-stream',
    'cache-control':'no-store'});
   res.end(data);
  }catch{res.writeHead(404);res.end('Not found');}
 });
}
function executable(){
 const paths=[process.env.CHROME_PATH,'/usr/bin/google-chrome',
  '/usr/bin/google-chrome-stable','/usr/bin/chromium','/usr/bin/chromium-browser'];
 const found=paths.find(p=>p&&fs.existsSync(p));
 if(!found)throw Error('System Chrome missing: offline acceptance cannot be skipped.');
 return found;
}
async function main(){
 const local=server();let browser;
 await new Promise(resolve=>local.listen(0,'127.0.0.1',resolve));
 try{
  const base='http://127.0.0.1:'+local.address().port+'/';
  browser=await chromium.launch({headless:true,executablePath:executable(),
    args:['--no-sandbox','--disable-dev-shm-usage']});
  const ctx=await browser.newContext({viewport:{width:393,height:852},
    deviceScaleFactor:2,isMobile:true,hasTouch:true,timezoneId:'Asia/Tokyo',
    locale:'de-DE',serviceWorkers:'allow',permissions:['geolocation'],
    geolocation:{latitude:35.01,longitude:135.77,accuracy:12}});
  // No requests to OSM, geocoders, Google, GitHub or any other external site.
  await ctx.route('**/*',route=>
    route.request().url().startsWith(base)?route.continue():route.abort());
  const page=await ctx.newPage();
  page.setDefaultTimeout(14000);
  const uncaught=[];
  page.on('pageerror',e=>uncaught.push(e.message));
  await page.goto(base+'?view=town-kyoto',{waitUntil:'domcontentloaded'});
  await page.locator('#plan-select').waitFor({state:'visible'});
  await page.waitForFunction(async()=>{
    if(!('serviceWorker' in navigator))return false;
    const reg=await navigator.serviceWorker.getRegistration('./');
    return !!reg?.active;
  },null,{timeout:24000});
  // An initial install may not yet control its first opened page.
  await page.reload({waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>!!navigator.serviceWorker?.controller,null,{timeout:14000});
  await page.locator('#plan-select').selectOption('ride-nikko');
  await page.waitForFunction(()=>
    document.querySelector('#plan-select')?.value==='ride-nikko',null,{timeout:14000});
  const before=await page.evaluate(async()=>{
    const shelf=new window.LivekarteTicketLibrary.Library();
    const pdf=new File(['%PDF-1.7\\nsynthetic-offline-test\\n%%EOF'],
      'preflight-demo.pdf',{type:'application/pdf'});
    const saved=await shelf.add(pdf,{title:'Nur CI-Testticket',trip:'Keine echte Buchung'});
    const record=await shelf.get(saved.id);
    const bytes=Array.from(new Uint8Array(await record.blob.arrayBuffer()));
    const plan=localStorage.getItem('livekarte-active-plan-v1');
    const cachesBefore=await caches.keys();
    return {id:saved.id,bytes,plan,
      count:(await shelf.list()).length,
      cacheNames:cachesBefore.filter(k=>k.startsWith('livekarte-shell-'))};
  });
  assert.equal(before.plan,'ride-nikko');
  assert.equal(before.count,1,'Test starts with precisely one synthetic ticket');
  assert.equal(before.cacheNames.length,1,'Install produces one offline shell cache');
  console.log('PASS installed service worker and synthetic IndexedDB ticket created');
  await ctx.setOffline(true);
  await page.reload({waitUntil:'domcontentloaded',timeout:18000});
  await page.locator('#plan-select').waitFor({state:'visible',timeout:14000});
  assert.equal(await page.locator('#plan-select').inputValue(),'ride-nikko');
  assert.equal(await page.locator('#nikko-tokyo-step-count').innerText(),
    'Schritt 1 von 3 · Nozomi 12 verlassen');
  const after=await page.evaluate(async ticketId=>{
    const shelf=new window.LivekarteTicketLibrary.Library();
    const record=await shelf.get(ticketId);
    const content=Array.from(new Uint8Array(await record.blob.arrayBuffer()));
    const names=await caches.keys();
    const cache=await caches.open(names.find(k=>k.startsWith('livekarte-shell-')));
    return {bytes:content,count:(await shelf.list()).length,
      plan:localStorage.getItem('livekarte-active-plan-v1'),
      hasApp:!!(await cache.match(new URL('app.js',location.href).href)),
      hasNewModule:!!(await cache.match(new URL('station-transfer-core.js',location.href).href)),
      hasPrivateData:names.some(k=>k.includes('ticket-library-v1')||k.includes('inbox'))};
  },before.id);
  assert.deepEqual(after.bytes,before.bytes,'PDF bytes must survive offline reload exactly');
  assert.equal(after.count,1,'No duplicate ticket after PWA restart');
  assert.equal(after.plan,before.plan,'Selected Nikkō journey survives offline restart');
  assert.equal(after.hasApp,true,'App shell cached');
  assert.equal(after.hasNewModule,true,'New station transfer module cached');
  assert.equal(after.hasPrivateData,false,'No ticket content may be cached in CacheStorage');
  assert.deepEqual(uncaught,[],'No browser runtime exceptions while starting offline');
  console.log('PASS real offline PWA restart preserves Nikkō rail view, ticket bytes and plan');
  await ctx.setOffline(false);
  await page.reload({waitUntil:'domcontentloaded'});
  const reconnected=await page.evaluate(async id=>{
    const shelf=new window.LivekarteTicketLibrary.Library();
    return {count:(await shelf.list()).length,
      saved:!!(await shelf.get(id)),
      plan:localStorage.getItem('livekarte-active-plan-v1')};
  },before.id);
  assert.equal(reconnected.count,1);
  assert.equal(reconnected.saved,true);
  assert.equal(reconnected.plan,'ride-nikko');
  console.log('PASS online return does not change stored tickets or selected travel section');
 }finally{
  if(browser)await browser.close();
  await new Promise(resolve=>local.close(resolve));
 }
}
main().catch(e=>{console.error('OFFLINE PWA PREFLIGHT FAILED:',e.stack||e);process.exitCode=1;});
